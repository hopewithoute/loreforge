import contextlib
import logging
import random
import uuid
from datetime import UTC, datetime, timedelta
from typing import cast

import fsspec
from sqlalchemy import CursorResult, select, update
from sqlalchemy.orm import Session

from app.core.errors import ErrorCode
from app.db.schema import Asset
from app.models.asset import AssetCreate, AssetEvolve, AssetRead, AssetStatus
from app.services.image_utils import prepare_provider_image

logger = logging.getLogger(__name__)
STALE_ASSET_THRESHOLD = timedelta(minutes=5)


class AssetService:
    def __init__(self, session: Session, storage: fsspec.AbstractFileSystem):
        self._db = session
        self._storage = storage

    def _get_asset_orm(self, asset_id: str, user_id: str) -> Asset | None:
        stmt = select(Asset).where(Asset.id == asset_id, Asset.user_id == user_id)
        return self._db.scalars(stmt).first()

    def has_pending_assets(self, user_id: str) -> bool:
        stmt = (
            select(Asset)
            .where(Asset.user_id == user_id, Asset.status == AssetStatus.pending.value)
            .limit(1)
        )
        return self._db.scalars(stmt).first() is not None

    def create_asset(
        self,
        user_id: str,
        data: AssetCreate,
        reference_bytes: bytes | None = None,
        reference_ext: str | None = None,
        existing_reference_id: str | None = None,
        sibling_id: str | None = None,
    ) -> AssetRead:
        # We allocate the asset ID early so we can use it to create
        # a strictly isolated directory for this asset's files.
        asset_id = str(uuid.uuid7())
        asset = Asset(
            id=asset_id,
            user_id=user_id,
            prompt=data.prompt,
            category=data.category.value,
            style=data.style.value,
            seed=random.randint(0, 4294967295),
        )

        if sibling_id:
            # Siblings are parallel variations (Regen/Retry) of the same conceptual generation step.
            # They share the same parent_id as the original asset, and their sibling_id points to the group root.
            original_asset = self._get_asset_orm(sibling_id, user_id)
            if original_asset:
                asset.parent_id = original_asset.parent_id
                asset.sibling_id = original_asset.sibling_id or original_asset.id

        try:
            # =====================================================================
            # STEP 1: PHYSICAL FILE PERSISTENCE
            # We handle disk I/O first before committing to the DB. If disk writes
            # fail, we don't end up with a ghost DB record pointing nowhere.
            # =====================================================================
            if reference_bytes and reference_ext:
                # PATH A: Brand new user-uploaded sketch.
                # Store the exact uploaded file for user reference/gallery viewing.
                original_path = f"assets/{asset_id}/original{reference_ext}"
                self._storage.pipe_file(original_path, reference_bytes)
                asset.reference_image_path = original_path

                # Create a downscaled copy specifically formatted for the AI provider
                # (e.g., max 511px for Cloudflare FLUX)
                prepared_bytes = prepare_provider_image(reference_bytes)
                prepared_path = f"assets/{asset_id}/prepared.png"
                self._storage.pipe_file(prepared_path, prepared_bytes)
                asset.prepared_input_path = prepared_path
            elif existing_reference_id:
                # PATH B: User clicked "REGEN". We are duplicating a previous asset's state.
                # We physically copy the images to ensure complete file isolation per asset_id.
                old_asset = self._get_asset_orm(existing_reference_id, user_id)
                if old_asset:
                    if old_asset.reference_image_path and old_asset.prepared_input_path:
                        # Case B1: The ancestor was a standard generation with an uploaded sketch.
                        new_ref_path = (
                            f"assets/{asset_id}/{old_asset.reference_image_path.split('/')[-1]}"
                        )
                        new_prep_path = f"assets/{asset_id}/prepared.png"
                        self._storage.copy(old_asset.reference_image_path, new_ref_path)
                        self._storage.copy(old_asset.prepared_input_path, new_prep_path)
                        asset.reference_image_path = new_ref_path
                        asset.prepared_input_path = new_prep_path
                    elif old_asset.prepared_input_path:
                        # Case B2: The ancestor was an Evolved asset. It doesn't have an original
                        # user upload, only the prepared image generated by the AI previously.
                        new_prep_path = f"assets/{asset_id}/prepared.png"
                        self._storage.copy(old_asset.prepared_input_path, new_prep_path)
                        asset.prepared_input_path = new_prep_path

            # =====================================================================
            # STEP 2: DATABASE PERSISTENCE
            # =====================================================================
            self._db.add(asset)
            self._db.commit()
            self._db.refresh(asset)
            return AssetRead.model_validate(asset)

        except Exception:
            # Step 3: Rollback & Cleanup on failure
            # If the database fails (e.g. SQLite locked), we must sweep any newly
            # created images to prevent orphan files on disk.
            self._db.rollback()
            with contextlib.suppress(FileNotFoundError):
                self._storage.rm(f"assets/{asset_id}", recursive=True)
            raise

    def get_asset(self, asset_id: str, user_id: str) -> AssetRead | None:
        asset = self._get_asset_orm(asset_id, user_id)
        return AssetRead.model_validate(asset) if asset else None

    def delete_asset(self, asset_id: str, user_id: str) -> bool:
        asset = self._get_asset_orm(asset_id, user_id)
        if not asset:
            return False

        # Gather all descendant IDs to prune the whole branch
        def get_descendants(parent_id: str) -> list[str]:
            desc_ids = []
            stmt = select(Asset.id).where(Asset.parent_id == parent_id)
            children = self._db.scalars(stmt).all()
            for child_id in children:
                desc_ids.append(child_id)
                desc_ids.extend(get_descendants(child_id))
            return desc_ids

        # ---------------------------------------------------------
        # NEW RULE: Re-parenting (Survivor Succession)
        # ---------------------------------------------------------
        # If the asset being deleted has siblings, we DO NOT prune its children.
        # Instead, we transfer custody of its children to the oldest surviving sibling,
        # and if the deleted asset was the root anchor, we promote the survivor to root.

        # 1. Find the sibling group ID
        group_id = asset.sibling_id or asset.id

        # 2. Find surviving siblings (ordered by oldest first)
        stmt = (
            select(Asset)
            .where(Asset.id != asset_id)
            .where((Asset.sibling_id == group_id) | (Asset.id == group_id))
            .order_by(Asset.created_at.asc())
        )
        survivors = self._db.scalars(stmt).all()

        if survivors:
            # We have an heir!
            heir = survivors[0]

            # 3. Transfer custody of direct children to the heir
            stmt_children = select(Asset).where(Asset.parent_id == asset_id)
            children = self._db.scalars(stmt_children).all()
            for child in children:
                child.parent_id = heir.id

            # 4. If the deleted asset was the root (anchor) of the sibling group,
            # we must promote the heir to be the new root.
            if asset.sibling_id is None:
                heir.sibling_id = None
                for other_survivor in survivors[1:]:
                    other_survivor.sibling_id = heir.id

            self._db.commit()

            # Since we reparented the children, we ONLY delete the asset itself.
            all_ids_to_delete = [asset_id]

        else:
            # No survivors. We prune the entire lineage.
            descendant_ids = get_descendants(asset_id)
            all_ids_to_delete = [asset_id, *descendant_ids]

        # Ground Truth Rule: Lineage Lockdown
        # Cannot delete if any of its members to be deleted is currently generating (pending)
        stmt_status = select(Asset.status).where(Asset.id.in_(all_ids_to_delete))
        statuses = self._db.scalars(stmt_status).all()
        if "pending" in statuses:
            raise ValueError("Cannot delete lineage with pending generations")

        try:
            # Delete from DB
            for d_id in reversed(all_ids_to_delete):
                a = self._db.scalar(select(Asset).where(Asset.id == d_id))
                if a:
                    self._db.delete(a)
            self._db.commit()

            # Delete from storage
            for d_id in all_ids_to_delete:
                with contextlib.suppress(FileNotFoundError):
                    self._storage.rm(f"assets/{d_id}", recursive=True)
            return True
        except Exception:
            self._db.rollback()
            raise

    def evolve_asset(self, parent_id: str, user_id: str, data: AssetEvolve) -> AssetRead | None:
        parent = self._get_asset_orm(parent_id, user_id)
        if not parent or not parent.generated_image_path:
            return None

        asset_id = str(uuid.uuid7())
        asset = Asset(
            id=asset_id,
            user_id=user_id,
            prompt=data.prompt,
            category=data.category.value,
            style=data.style.value,
            seed=random.randint(0, 4294967295),
            parent_id=parent_id,
            sibling_id=None,
        )

        try:
            # =====================================================================
            # EVOLUTION LOGIC:
            # Instead of a user upload, the newly evolved asset takes the FINAL
            # generated image of its parent and sets it as its own INPUT reference.
            # =====================================================================
            parent_image_bytes = cast(bytes, self._storage.cat_file(parent.generated_image_path))
            prepared_bytes = prepare_provider_image(parent_image_bytes)

            prepared_path = f"assets/{asset_id}/prepared.png"
            self._storage.pipe_file(prepared_path, prepared_bytes)
            asset.prepared_input_path = prepared_path

            self._db.add(asset)
            self._db.commit()
            self._db.refresh(asset)
            return AssetRead.model_validate(asset)
        except Exception:
            self._db.rollback()
            with contextlib.suppress(FileNotFoundError):
                self._storage.rm(f"assets/{asset_id}", recursive=True)
            raise

    def list_assets(self, user_id: str) -> list[AssetRead]:
        stmt = select(Asset).where(Asset.user_id == user_id).order_by(Asset.created_at.desc())
        return [AssetRead.model_validate(a) for a in self._db.scalars(stmt)]

    def _transition_pending(
        self,
        asset_id: str,
        user_id: str,
        status: AssetStatus,
        values: dict[str, object],
    ) -> AssetRead | None:
        """
        Safely transitions an asset OUT of the 'pending' state.
        This uses an atomic UPDATE WHERE status = pending.

        While strict race condition protection might be overkill for our
        current traffic level, this atomic approach is just as simple (if not
        simpler) than a naive read-then-update pattern. Building in concurrency
        safety from day one with zero extra overhead is good.
        """
        stmt = (
            update(Asset)
            .where(
                Asset.id == asset_id,
                Asset.user_id == user_id,
                Asset.status == AssetStatus.pending.value,
            )
            .values(status=status.value, **values)
        )

        result = cast(CursorResult, self._db.execute(stmt))
        self._db.commit()

        if result.rowcount == 0:
            return None

        # Fetch and return the updated state
        asset = self._get_asset_orm(asset_id, user_id)
        assert asset is not None, f"Row {asset_id} vanished after successful UPDATE"
        return AssetRead.model_validate(asset)

    def mark_as_success(
        self,
        asset_id: str,
        user_id: str,
        generated_image_path: str,
        provider_name: str,
        provider_model: str,
        seed: int | None,
    ) -> AssetRead | None:
        return self._transition_pending(
            asset_id,
            user_id,
            status=AssetStatus.success,
            values={
                "generated_image_path": generated_image_path,
                "provider_name": provider_name,
                "provider_model": provider_model,
                "seed": seed,
            },
        )

    def mark_as_failed(
        self,
        asset_id: str,
        user_id: str,
        error_code: ErrorCode,
        error_message: str,
    ) -> AssetRead | None:
        return self._transition_pending(
            asset_id,
            user_id,
            status=AssetStatus.failed,
            values={
                "error_code": error_code,
                "error_message": error_message,
            },
        )


def reconcile_stale_assets(db: Session, threshold: timedelta | None = None) -> int:
    """
    Reconcile stale pending assets that were interrupted by a server restart.
    Marks them as failed so they don't stay pending forever.
    Only targets assets older than the given threshold (default 5 minutes).
    In Our Case its default to 0 seconds, since the service is single instance.
    """
    active_threshold = threshold if threshold is not None else STALE_ASSET_THRESHOLD
    stale_threshold = datetime.now(UTC) - active_threshold

    stmt = (
        update(Asset)
        .where(Asset.status == AssetStatus.pending.value, Asset.created_at < stale_threshold)
        .values(
            status=AssetStatus.failed.value,
            error_code=ErrorCode.INTERNAL_ERROR,
            error_message="Generation interrupted by server restart.",
        )
    )

    result = cast(CursorResult, db.execute(stmt))
    db.commit()

    if result.rowcount > 0:
        logger.info(f"Reconciled {result.rowcount} stale pending assets to failed state.")

    return result.rowcount
